class AssessmentResponse(BaseModel):
    """
    Complete KiranaIQ assessment result.

    This is the canonical output format promised in the Round 1 pitch deck.
    Every field shown in the slide 4 JSON specimen is present here.
    The Streamlit dashboard reads exclusively from this model.
    """

    # Identity
    assessment_id: str = Field(
        ...,
        description="Unique assessment identifier (e.g., 'KIQ-A1B2C3D4E5F6').",
    )
    processing_time_ms: int = Field(
        ...,
        description="Total server-side processing time in milliseconds.",
    )
    mode: str = Field(
        ...,
        description="Runtime mode at time of assessment: 'demo' or 'production'.",
    )

    # Core cash flow estimates
    daily_sales_range: List[int] = Field(
        ...,
        min_length=2,
        max_length=2,
        description="Estimated daily sales range [lower, upper] in ₹.",
    )
    monthly_revenue_range: List[int] = Field(
        ...,
        min_length=2,
        max_length=2,
        description="Estimated gross monthly revenue range [lower, upper] in ₹.",
    )
    monthly_income_range: List[int] = Field(
        ...,
        min_length=2,
        max_length=2,
        description="Estimated net monthly income range [lower, upper] in ₹ after rent.",
    )
    interval_coverage: float = Field(
        default=0.80,
        description=(
            "Statistical coverage guarantee of the reported intervals. "
            "0.80 = these ranges will contain the true value 80% of the time."
        ),
    )

    # Economic sub-models
    income_calculation: IncomeCalculation
    seasonality: SeasonalityProfile
    peer_benchmark: PeerBenchmark

    # Credit output
    recommended_credit_limit: List[int] = Field(
        ...,
        min_length=2,
        max_length=2,
        description="Recommended credit limit range [lower, upper] in ₹.",
    )
    emi_affordability_score: int = Field(
        ...,
        ge=0,
        le=100,
        description=(
            "EMI affordability score (0–100). "
            "75+ = strong, 50–74 = moderate, <50 = caution."
        ),
    )

    # Store signals
    store_type: str = Field(
        ...,
        description=(
            "Classified store archetype: "
            "'kirana_primary' | 'kirana_pharma_hybrid' | "
            "'kirana_mobile_hybrid' | 'general_store'."
        ),
    )
    category_mix: Dict[str, float] = Field(
        ...,
        description="Category weight vector (e.g., {'staples': 0.42, 'fmcg': 0.31}).",
    )
    fmvc_ratio: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Fast-Moving vs. Slow-Moving inventory ratio. "
            "Higher = better cash conversion velocity."
        ),
    )

    # Confidence
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Composite confidence score (0–1).",
    )
    confidence_tier: str = Field(
        ...,
        description=(
            "Named confidence tier: "
            "'high' (≥0.80) | 'medium' (≥0.60) | "
            "'low' (≥0.40) | 'insufficient' (<0.40)."
        ),
    )
    confidence_tier_interpretation: str = Field(
        ...,
        description="One-sentence human-readable explanation of the confidence tier.",
    )
    confidence_breakdown: ConfidenceBreakdown

    # Fraud
    fraud_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Composite fraud score (0 = clean, 1 = certain fraud).",
    )
    fraud_flags: List[str] = Field(
        default_factory=list,
        description="Fraud-specific flags raised (e.g., 'hmac_binding_failure').",
    )
    risk_flags: List[str] = Field(
        default_factory=list,
        description="Non-fraud risk flags (e.g., 'low_light_enhanced', 'rent_not_declared').",
    )
    temporal: TemporalFraudScores

    # Processing metadata
    cascade_tier: CascadeTierInfo

    # Decision
    recommendation: str = Field(
        ...,
        description=(
            "Underwriting recommendation: "
            "'approve' | 'approve_with_monitoring' | "
            "'needs_field_verification' | "
            "'reject_fraud_suspected' | 'reject_insufficient_income'."
        ),
    )
    underwriter_narrative: str = Field(
        ...,
        description=(
            "Plain-English credit summary for the underwriter. "
            "References key signal drivers and the recommendation rationale."
        ),
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "assessment_id": "KIQ-A1B2C3D4E5F6",
                "processing_time_ms": 312,
                "mode": "demo",
                "daily_sales_range": [6200, 8800],
                "monthly_revenue_range": [186000, 264000],
                "monthly_income_range": [28000, 44000],
                "interval_coverage": 0.80,
                "confidence_score": 0.74,
                "confidence_tier": "medium",
                "confidence_tier_interpretation": (
                    "Sufficient for conditional approval. "
                    "One or more signals require field confirmation."
                ),
                "fraud_score": 0.11,
                "fraud_flags": [],
                "risk_flags": ["rent_not_declared_using_area_prior"],
                "recommendation": "approve_with_monitoring",
                "underwriter_narrative": (
                    "Store shows consistent FMCG mix. SDI 0.74. "
                    "Arterial road + bus depot 38m. Peer 67th percentile. "
                    "Approve at lower bound. 3-month review recommended."
                ),
            }
        }
    )


