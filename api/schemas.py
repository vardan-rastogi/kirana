"""
Pydantic request and response models for the KiranaIQ assessment API.

These schemas are the single contract between the FastAPI backend and the
Streamlit frontend. Both engineers code against these models exclusively.
No field may be added to the API response without first adding it here.

All monetary values are in Indian Rupees (₹) as integers.
All scores are floats in the range [0.0, 1.0] unless otherwise noted.
All ranges are two-element lists [lower_bound, upper_bound].
"""

from __future__ import annotations

import time
from typing import Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator


# ---------------------------------------------------------------------------
# Request model
# ---------------------------------------------------------------------------

class AssessmentRequest(BaseModel):
    """
    Payload sent by the Streamlit frontend (or field agent SDK) to initiate
    a KiranaIQ cash flow assessment.

    Images are sent as multipart/form-data files alongside this form data.
    """

    gps_lat: float = Field(
        ...,
        ge=6.0,
        le=37.5,
        description="Decimal degrees latitude. Must be within India bounds.",
        examples=[21.1458],
    )
    gps_lon: float = Field(
        ...,
        ge=68.0,
        le=97.5,
        description="Decimal degrees longitude. Must be within India bounds.",
        examples=[79.0882],
    )
    capture_timestamp: int = Field(
        default_factory=lambda: int(time.time()),
        description="Unix epoch timestamp of image capture. Used for HMAC binding.",
    )
    hmac_commitments: List[str] = Field(
        default_factory=list,
        min_length=0,
        max_length=5,
        description=(
            "Per-image HMAC-SHA256 commitments generated by the Android SDK "
            "at capture time. Empty list is accepted in demo mode."
        ),
    )
    shop_size_sqft: Optional[int] = Field(
        None,
        ge=10,
        le=5000,
        description="Self-reported shop floor area in square feet.",
    )
    monthly_rent_inr: Optional[int] = Field(
        None,
        ge=0,
        le=500_000,
        description=(
            "Monthly rent in INR. Set to 0 only when property_owned=True. "
            "If property_owned=False and this is 0 or None, the geo-prior "
            "for the area is used as a fallback."
        ),
    )
    property_owned: bool = Field(
        default=False,
        description=(
            "True if the merchant owns the commercial property. "
            "Bypasses rent geo-prior fraud checks and applies the "
            "property ownership confidence premium (1.08×)."
        ),
    )
    years_in_operation: Optional[int] = Field(
        None,
        ge=0,
        le=60,
        description=(
            "Self-reported years the store has been operating. "
            "Used to compute the Lindy Effect vintage confidence multiplier."
        ),
    )
    sdk_attested: bool = Field(
        default=False,
        description=(
            "True if the Android SDK passed Play Integrity attestation. "
            "In demo mode this is always accepted as-is."
        ),
    )

    @field_validator("capture_timestamp")
    @classmethod
    def timestamp_not_in_future(cls, v: int) -> int:
        """Reject timestamps more than 5 minutes in the future (clock skew tolerance)."""
        now = int(time.time())
        if v > now + 300:
            raise ValueError(
                f"capture_timestamp {v} is in the future. "
                "Possible GPS binding attack or device clock error."
            )
        return v

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "gps_lat": 21.1458,
                "gps_lon": 79.0882,
                "capture_timestamp": 1714500000,
                "hmac_commitments": [],
                "shop_size_sqft": 80,
                "monthly_rent_inr": 8000,
                "property_owned": False,
                "years_in_operation": 14,
                "sdk_attested": False,
            }
        }
    )


