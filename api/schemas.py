class IncomeCalculation(BaseModel):
    """
    Transparent breakdown of the gross → net income derivation.
    Every line item must be present so the RBI audit trail is complete.
    """

    gross_monthly_range: List[int] = Field(
        ...,
        description="Gross income estimate before OPEX deductions. [lower, upper] ₹.",
    )
    rent_deducted: int = Field(
        ...,
        description="Effective monthly rent deducted (₹). Zero if property_owned=True.",
    )
    rent_source: str = Field(
        ...,
        description=(
            "Origin of the rent figure: "
            "'declared' | 'geo_prior' | 'zero_owned'."
        ),
    )
    property_owned: bool = Field(
        ...,
        description="Whether the merchant owns their commercial property.",
    )
    ownership_premium: float = Field(
        ...,
        description=(
            "Confidence multiplier applied for property ownership. "
            "1.08 if owned, 1.00 if renting."
        ),
    )
    rent_flags: List[str] = Field(
        default_factory=list,
        description="Any rent-specific fraud or risk flags raised.",
    )


class SeasonalityProfile(BaseModel):
    """
    12-month income simulation derived from category mix × seasonal indices.
    Used to compute the step-EMI schedule and trough-based EMI ceiling.
    """

    monthly_estimates: List[int] = Field(
        ...,
        description="Estimated net income for each of the 12 calendar months (₹).",
        min_length=12,
        max_length=12,
    )
    trough_month: str = Field(
        ...,
        description="Name of the lowest-income month (e.g., 'July').",
    )
    trough_income: int = Field(
        ...,
        description="Estimated income in the trough month (₹).",
    )
    peak_month: str = Field(
        ...,
        description="Name of the highest-income month (e.g., 'November').",
    )
    peak_income: int = Field(
        ...,
        description="Estimated income in the peak month (₹).",
    )
    seasonality_risk_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Coefficient of variation of monthly income. "
            "0 = perfectly stable, 1 = highly seasonal."
        ),
    )
    recommended_emi_ceiling: int = Field(
        ...,
        description=(
            "Maximum safe EMI (₹), computed as trough_income × 40% FOIR. "
            "This is the most conservative, RBI-defensible EMI figure."
        ),
    )
    step_emi_schedule: str = Field(
        ...,
        description=(
            "Human-readable step-EMI recommendation "
            "(e.g., '₹6,000/mo Jul–Aug · ₹10,000/mo rest of year')."
        ),
    )


class TemporalFraudScores(BaseModel):
    """
    Results from the on-device (or server-side in production) temporal
    fraud analysis of the optional 10-second video submission.
    Sentinel value -1.0 means the check was bypassed (e.g., luminance gate).
    """

    t1_staging_score: float = Field(
        ...,
        ge=-1.0,
        le=1.0,
        description=(
            "Inventory staging score. Histogram similarity between first and "
            "last video frame. > 0.5 suggests borrowed/staged goods. "
            "-1.0 = not computed."
        ),
    )
    t2_static_bg_score: float = Field(
        ...,
        ge=-1.0,
        le=1.0,
        description=(
            "Static background score. Optical flow foreground/background "
            "differential. > 0.5 suggests deepfake backdrop. -1.0 = bypassed."
        ),
    )
    t3_occlusion_score: float = Field(
        ...,
        ge=-1.0,
        le=1.0,
        description=(
            "Hand occlusion score. Skin-tone pixel ratio in shelf region. "
            "> 0.5 suggests hand-held inventory. -1.0 = bypassed."
        ),
    )
    luminance_mean: float = Field(
        default=-1.0,
        description=(
            "Mean frame luminance (0–255 scale). "
            "< 35 = luminance gate active, T-2/T-3 bypassed."
        ),
    )
    pipeline_bypassed: bool = Field(
        default=False,
        description="True if luminance was too low to run optical flow reliably.",
    )
    flags: List[str] = Field(
        default_factory=list,
        description="Temporal fraud flags raised (e.g., 'temporal_inventory_staging_suspected').",
    )
    video_submitted: bool = Field(
        default=False,
        description="False if no video was uploaded; temporal checks were not attempted.",
    )


class PeerBenchmark(BaseModel):
    """
    Comparison of this store against verified peer stores with similar
    geographic and operational profiles.
    """

    peer_count: int = Field(
        ...,
        description="Number of verified peer stores used in this benchmarking.",
    )
    income_percentile: int = Field(
        ...,
        ge=0,
        le=100,
        description="This store's estimated income percentile among peers (0–100).",
    )
    peer_median_daily_sales: int = Field(
        ...,
        description="Median daily sales of peer stores (₹).",
    )
    peer_p25_daily_sales: int = Field(
        ...,
        description="25th percentile daily sales of peer stores (₹).",
    )
    peer_p75_daily_sales: int = Field(
        ...,
        description="75th percentile daily sales of peer stores (₹).",
    )
    footfall_opportunity_score: float = Field(
        ...,
        description=(
            "Estimated under-earning relative to location potential. "
            "Positive = store earns less than location supports (growth capacity). "
            "Negative = store over-earns (may be unsustainable)."
        ),
    )
    benchmark_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Reliability of this benchmark. Low if peer_count < 10.",
    )


class ConfidenceBreakdown(BaseModel):
    """
    Transparent decomposition of the composite confidence score.
    Required for RBI Digital Lending Guidelines explainability compliance.
    """

    image_quality: float = Field(..., ge=0.0, le=1.0)
    signal_consistency: float = Field(..., ge=0.0, le=1.0)
    geo_completeness: float = Field(..., ge=0.0, le=1.0)
    fraud_clear: float = Field(..., ge=0.0, le=1.0)
    model_certainty: float = Field(..., ge=0.0, le=1.0)
    vintage_multiplier: float = Field(..., ge=0.0, le=1.1)
    fraud_penalty: float = Field(..., ge=0.0, le=1.0)
    ownership_premium: float = Field(..., ge=0.0, le=1.1)
    vintage_label: str = Field(
        ...,
        description="Human-readable vintage category (e.g., 'established', 'legacy_lindy').",
    )


class CascadeTierInfo(BaseModel):
    """
    Which processing tier was used and its associated cost.
    Displayed in the Streamlit UI as a badge.
    """

    tier: int = Field(..., description="0, 1, 2, or 3.")
    tier_label: str = Field(
        ...,
        description="Human-readable tier name (e.g., 'Tier 2 — Structured').",
    )
    estimated_cost_inr: int = Field(
        ...,
        description="Approximate API cost for this assessment (₹).",
    )
    providers_used: List[str] = Field(
        ...,
        description="Names of providers invoked (e.g., ['MockVision', 'MockGeo']).",
    )


